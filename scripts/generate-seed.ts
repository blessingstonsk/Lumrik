/**
 * Generates supabase/seed.sql from the TypeScript content sources.
 *   npm run seed:generate
 * Re-running is safe: every insert is an upsert.
 */
import { writeFileSync } from "node:fs";
import { BUILTIN } from "../src/content/index";
import { LANGUAGES } from "../src/lib/languages";
import { ACHIEVEMENTS } from "../src/lib/gamification";

const s = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return v.length ? `array[${v.map(s).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const j = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;

const out: string[] = [
  "-- AUTO-GENERATED by scripts/generate-seed.ts – do not edit by hand.",
  "begin;",
  "",
  "-- Languages",
];

for (const l of LANGUAGES) {
  out.push(
    `insert into public.languages (code, name, native_name, flag, glyph, script, speech_locale, rtl, enabled) values (${[l.code, l.name, l.nativeName, l.flag, l.glyph, l.script, l.speechLocale, !!l.rtl, l.enabled].map(s).join(", ")})` +
      ` on conflict (code) do update set name = excluded.name, native_name = excluded.native_name, flag = excluded.flag, glyph = excluded.glyph, script = excluded.script, speech_locale = excluded.speech_locale;`,
  );
}

out.push("", "-- Achievements");
for (const a of ACHIEVEMENTS) {
  out.push(
    `insert into public.achievements (id, title, description, icon, tier, metric, target) values (${[a.id, a.title, a.description, a.icon, a.tier, a.metric, a.target].map(s).join(", ")})` +
      ` on conflict (id) do update set title = excluded.title, description = excluded.description, icon = excluded.icon, tier = excluded.tier, metric = excluded.metric, target = excluded.target;`,
  );
}

for (const c of BUILTIN.courses) {
  out.push("", `-- Course: ${c.title}`);
  out.push(
    `insert into public.courses (id, target_lang, title, description, published) values (${[c.id, c.targetLang, c.title, c.description, c.published].map(s).join(", ")})` +
      ` on conflict (id) do update set title = excluded.title, description = excluded.description;`,
  );
  for (const u of c.units) {
    out.push(
      `insert into public.units (id, course_id, position, title, description, cefr, icon, published) values (${[u.id, c.id, u.order, u.title, u.description, u.cefr, u.icon, u.published].map(s).join(", ")})` +
        ` on conflict (id) do update set title = excluded.title, description = excluded.description, cefr = excluded.cefr, icon = excluded.icon;`,
    );
  }
}

out.push("", "-- Lessons & exercises");
for (const l of BUILTIN.lessons) {
  out.push(
    `insert into public.lessons (id, unit_id, position, title, description, tip, xp_reward, published) values (${[l.id, l.unitId, l.order, l.title, l.description, l.tip ?? null, l.xpReward, l.published].map(s).join(", ")})` +
      ` on conflict (id) do update set title = excluded.title, description = excluded.description, tip = excluded.tip, xp_reward = excluded.xp_reward;`,
  );
  for (const e of l.exercises) {
    out.push(
      `insert into public.exercises (id, lesson_id, position, type, instruction, data, explanation, word_ids) values (${[e.id, l.id, e.order, e.data.type, e.instruction].map(s).join(", ")}, ${j(e.data)}, ${s(e.explanation)}, ${s(e.wordIds)})` +
        ` on conflict (id) do update set position = excluded.position, type = excluded.type, instruction = excluded.instruction, data = excluded.data, explanation = excluded.explanation, word_ids = excluded.word_ids;`,
    );
  }
}

out.push("", "-- Vocabulary");
for (const v of BUILTIN.vocab) {
  out.push(
    `insert into public.vocabulary (id, course_id, lesson_id, term, meaning, pronunciation, part_of_speech, example, related, emoji) values (${[v.id, v.courseId, v.lessonId, v.term, v.meaning, v.pronunciation, v.partOfSpeech, v.example].map(s).join(", ")}, ${s(v.related)}, ${s(v.emoji ?? null)})` +
      ` on conflict (id) do update set meaning = excluded.meaning, pronunciation = excluded.pronunciation, part_of_speech = excluded.part_of_speech, example = excluded.example, related = excluded.related, emoji = excluded.emoji;`,
  );
}

out.push("", "commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"), "utf8");
console.log(`Wrote supabase/seed.sql: ${BUILTIN.lessons.length} lessons, ${BUILTIN.lessons.reduce((n, l) => n + l.exercises.length, 0)} exercises, ${BUILTIN.vocab.length} words.`);
